const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
assert.ok(fs.existsSync(path.join(root,'dist/assets/core.js')), '缺少时代筛选与投影实现');
const box = {window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'dist/assets/core.js'),'utf8'),box);
const {visibleCanals,project,formatYear} = box.window.AtlasCore;
const d = JSON.parse(fs.readFileSync(path.join(root,'data/atlas.json'),'utf8'));
assert.ok(visibleCanals(d,'sui','new').every(c=>c.era==='sui'));
assert.ok(!visibleCanals(d,'sui','network').some(c=>c.id==='huitong'), '隋代不能出现元代河道');
assert.ok(visibleCanals(d,'ming','network').some(c=>c.id==='jiangnan'), '明代应包含沿用的江南运河');
assert.ok(!visibleCanals(d,'ming','network').some(c=>c.id==='tonghui'), '明代应展示改治后的通惠河，而不是原样延续元代全线');
assert.equal(visibleCanals(d,'sui','all').length,d.canals.length);
assert.ok(project([116,40])[1] < project([116,30])[1], '北方必须在图上方');
assert.equal(formatYear(-214),'前214年');
assert.equal(formatYear(1293),'1293年');
for (const era of d.eras) assert.ok(visibleCanals(d,era.id,'network').length>0, era.id+' 不能为空');
console.log('PASS: 朝代筛选、沿用、新建、历代叠加、经纬投影及纪年。');
